import { useLayoutEffect, useRef, useState } from 'react'
import axios from 'axios'
import Disclosure from './Disclosure'
import Icon from './Icon'
import { useArrival } from '../lib/motion'

const API_URL = import.meta.env.VITE_API_URL || '/api'

export default function CurveballPractice({ definition, session, code, transcript, disabled, onSpeak, onReturnToOriginal, onRunResult }) {
  const [result, setResult] = useState(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')
  const requestRef = useRef(null)
  const resultRef = useRef(null)
  useArrival(resultRef, result)

  useLayoutEffect(() => {
    requestRef.current?.abort()
    requestRef.current = null
    setLoading(false)
    setResult(null)
    setError('')
    return () => requestRef.current?.abort()
  }, [code, transcript, session])

  async function review() {
    if (disabled || requestRef.current || !transcript.trim()) return
    const controller = new AbortController()
    requestRef.current = controller
    setLoading(true); setError(''); setResult(null)
    try {
      const { data } = await axios.post(`${API_URL}/curveball/review`, {
        problemId: definition.problemId, curveballId: definition.id,
        beforeCode: session.code, beforeTranscript: session.transcript, code, transcript,
      }, { signal: controller.signal, timeout: 60000 })
      if (controller.signal.aborted || requestRef.current !== controller) return
      if (!data.run || !Array.isArray(data.run.results) || !data.feedback ||
          typeof data.feedback.summary !== 'string' || !data.feedback.summary.trim() ||
          typeof data.feedback.nextStep !== 'string' || !data.feedback.nextStep.trim() || !Array.isArray(data.feedback.checks) ||
          data.feedback.checks.length !== 3 || data.feedback.checks.some(check =>
            !['requirementUnderstanding', 'adaptation', 'verification'].includes(check.id) ||
            typeof check.met !== 'boolean' || typeof check.label !== 'string' || typeof check.note !== 'string' ||
            (check.quote !== null && typeof check.quote !== 'string'))) {
        throw new Error('The review was incomplete. Your code and explanation are still here; try again.')
      }
      setResult(data)
      onSpeak?.(data.feedback.summary)
      onRunResult(data.run)
    } catch (err) {
      if (controller.signal.aborted || requestRef.current !== controller) return
      setError(err.response?.data?.error || err.message || 'Could not review your adaptation. You can still run the new test cases.')
    } finally {
      if (!controller.signal.aborted && requestRef.current === controller) {
        requestRef.current = null
        setLoading(false)
      }
    }
  }

  if (!definition || !session) return null
  return <section className={`curveball-practice${session ? ' curveball-active' : ''}`} aria-labelledby="curveball-title">
    <h3 id="curveball-title"><Icon name="arrow" size={16} />Interview curveball</h3>
    <>
      <p className="curveball-requirement" role="status"><strong>{definition.title}</strong> {definition.prompt}</p>
      <p>{definition.requirement}</p>
      <p className="curveball-note">Generated by AI. Test expectations are checked by the server. This requirement expires after one hour or a backend restart.</p>
      <p className="curveball-instruction">Update your code and live explanation, then run the new cases. The updated requirements are shown below.</p>
      <Disclosure className="curveball-baseline"><summary>Before the requirement changed</summary>
        <p>Your code</p><pre><code>{session.code}</code></pre>
        <p>Your explanation</p><blockquote>{session.transcript || 'No explanation captured yet.'}</blockquote>
      </Disclosure>
      <button className="learning-secondary" onClick={review} disabled={disabled || loading || !transcript.trim()}>
        {loading ? 'Reviewing adaptation…' : 'Review my adaptation'}
      </button>
      <button className="btn-text" disabled={disabled} onClick={onReturnToOriginal}>Return to original requirements</button>
      <p className="curveball-note">Review sends the original and current code and explanation to your selected AI provider. You can run tests without AI.</p>
      {error && <p className="curveball-error" role="alert">{error}</p>}
      {result && <div ref={resultRef} className="curveball-review" role="status">
        <h4>Your adaptation review</h4>
        <p>{result.run.passed}/{result.run.total} code checks passed.</p>
        <p>{result.feedback.summary}</p>
        <ul>{result.feedback.checks.map(check => <li key={check.id}>
          <strong>{check.label}: {check.met ? 'Supported' : 'Not evidenced'}</strong>
          <p>{check.note}</p>
          {check.quote && transcript.includes(check.quote) && <blockquote>“{check.quote}”</blockquote>}
        </li>)}</ul>
        <p><strong>Next step:</strong> {result.feedback.nextStep}</p>
        <p className="curveball-note">AI feedback reflects the explanation you provided. Passing tests and demonstrated reasoning are separate signals. This review stays in this session.</p>
      </div>}
    </>
  </section>
}
